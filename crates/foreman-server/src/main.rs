mod api;
mod config;

use api::ws::WsState;
use axum::{
    routing::{get, get_service},
    Router,
};
use foreman_core::events::ServerEvent;
use std::{net::SocketAddr, path::PathBuf, sync::Arc, time::Duration};
use tokio::{signal, sync::broadcast};
use tower_http::{
    cors::CorsLayer,
    services::{ServeDir, ServeFile},
    trace::TraceLayer,
};
use tracing::{info, warn};

#[tokio::main]
async fn main() {
    // Initialise logging. RUST_LOG controls filtering; default to info.
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "foreman_server=info,tower_http=warn".parse().unwrap()),
        )
        .init();

    let cfg = config::ServerConfig::load();
    info!(
        port = cfg.port,
        host = %cfg.host,
        data_dir = %cfg.data_dir.display(),
        db_url = cfg.db_url.as_deref().unwrap_or("(none)"),
        "foreman-server starting"
    );

    // Ensure data dir exists
    if let Err(err) = std::fs::create_dir_all(&cfg.data_dir) {
        warn!(
            "could not create data dir {}: {err}",
            cfg.data_dir.display()
        );
    }

    // Broadcast bus — 256-slot ring buffer.
    let (tx, _) = broadcast::channel::<ServerEvent>(256);
    let tx = Arc::new(tx);

    // Heartbeat task: publish a heartbeat every 10 s.
    {
        let tx = Arc::clone(&tx);
        tokio::spawn(async move {
            let mut interval = tokio::time::interval(Duration::from_secs(10));
            loop {
                interval.tick().await;
                // If no subscribers, the send fails but that's fine.
                let _ = tx.send(ServerEvent::heartbeat());
            }
        });
    }

    let ws_state = WsState { tx };

    // Static file serving for the frontend.
    // `frontend/dist` is generated by `npm run build` (session 2+).
    // Falls back gracefully when the directory doesn't exist yet.
    let frontend_dist = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent() // crates/
        .and_then(|p| p.parent()) // repo root
        .map(|r| r.join("frontend/dist"))
        .unwrap_or_else(|| PathBuf::from("frontend/dist"));

    let spa_fallback = frontend_dist.join("index.html");

    let static_service = if frontend_dist.exists() {
        get_service(ServeDir::new(&frontend_dist).fallback(ServeFile::new(&spa_fallback)))
    } else {
        // During scaffold, frontend/dist doesn't exist yet — serve a stub.
        get_service(ServeDir::new(&frontend_dist))
    };

    let app = Router::new()
        .route("/api/health", get(api::health::health))
        .route("/ws/events", get(api::ws::ws_handler))
        .fallback_service(static_service)
        .with_state(ws_state)
        .layer(TraceLayer::new_for_http())
        .layer(CorsLayer::permissive());

    let addr: SocketAddr = format!("{}:{}", cfg.host, cfg.port)
        .parse()
        .unwrap_or_else(|_| SocketAddr::from(([127, 0, 0, 1], 9090)));

    let listener = tokio::net::TcpListener::bind(addr)
        .await
        .unwrap_or_else(|err| {
            eprintln!("failed to bind {addr}: {err}");
            std::process::exit(1);
        });

    info!("listening on http://{addr}");
    info!("health: http://{addr}/api/health");
    info!("events: ws://{addr}/ws/events");

    axum::serve(listener, app)
        .with_graceful_shutdown(shutdown_signal())
        .await
        .unwrap_or_else(|err| {
            eprintln!("server error: {err}");
            std::process::exit(1);
        });

    info!("foreman-server stopped");
}

/// Waits for Ctrl+C (all platforms) or SIGTERM (Unix).
async fn shutdown_signal() {
    let ctrl_c = async {
        signal::ctrl_c()
            .await
            .expect("failed to install Ctrl+C handler");
    };

    #[cfg(unix)]
    let terminate = async {
        signal::unix::signal(signal::unix::SignalKind::terminate())
            .expect("failed to install SIGTERM handler")
            .recv()
            .await;
    };

    #[cfg(not(unix))]
    let terminate = std::future::pending::<()>();

    tokio::select! {
        _ = ctrl_c => { info!("received Ctrl+C, shutting down"); },
        _ = terminate => { info!("received SIGTERM, shutting down"); },
    }
}
